"""Stage a clean backend using the current platform's managed Python."""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import tempfile
from pathlib import Path


def assert_clean_backend(stage: Path) -> None:
    """Fail before packaging if probes or bytecode leaked into runtime resources."""
    for name in ("python", "site-packages", "backend/app"):
        if not (stage / name).is_dir():
            raise ValueError("Staged backend layout is incomplete")
    if (stage / "data").exists() or (stage / "verify.py").exists():
        raise ValueError("Staging probe files must not ship")
    if any(path.name == "__pycache__" or path.suffix in (".pyc", ".pyo")
           for path in stage.rglob("*")):
        raise ValueError("Generated Python bytecode must not ship")


def stage_backend(repo: Path, output: Path | None = None) -> Path:
    python = repo / (
        "backend/.venv/Scripts/python.exe"
        if os.name == "nt"
        else "backend/.venv/bin/python"
    )
    info = json.loads(
        subprocess.check_output(
            [
                str(python),
                "-c",
                "import json,sys,sysconfig; print(json.dumps({'base':sys.base_prefix,'packages':sysconfig.get_path('purelib'),'version':list(sys.version_info[:2])}))",
            ],
            text=True,
        )
    )
    if info["version"] != [3, 12]:
        raise ValueError("The bundled backend requires Python 3.12")
    try:
        version = json.loads((repo / "desktop/src-tauri/tauri.conf.json").read_text(encoding="utf-8"))["version"]
    except (OSError, ValueError, KeyError, TypeError) as error:
        raise ValueError("Invalid product version metadata") from error
    if not isinstance(version, str) or not re.fullmatch(r"[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.-]+)?", version):
        raise ValueError("Invalid product version metadata")
    stage = output or Path(tempfile.mkdtemp(prefix="ripple-backend-sidecar-"))
    if output:
        stage.mkdir(parents=True, exist_ok=False)
    ignore = shutil.ignore_patterns("__pycache__", "*.pyc", "*.pyo")
    shutil.copytree(Path(info["base"]), stage / "python", ignore=ignore)
    shutil.copytree(Path(info["packages"]), stage / "site-packages", ignore=ignore)
    shutil.copytree(repo / "backend/app", stage / "backend/app", ignore=ignore)
    (stage / "mock-data").mkdir()
    for name in ("sample-transcript.json", "sample-metadata.json"):
        shutil.copy2(repo / "mock-data" / name, stage / "mock-data" / name)
    (stage / "product-version.json").write_text(json.dumps({"version": version}) + "\n", encoding="utf-8")
    (stage / "data").mkdir()
    shutil.copy2(
        Path(__file__).with_name("verify-staged-backend.py"), stage / "verify.py"
    )
    return stage


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--output", type=Path)
    mode.add_argument("--check-clean", type=Path)
    args = parser.parse_args()
    if args.check_clean:
        assert_clean_backend(args.check_clean)
        print("Staged backend contains no probe data or generated bytecode")
    else:
        print(stage_backend(Path(__file__).resolve().parents[1], args.output))
